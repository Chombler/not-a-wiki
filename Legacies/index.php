	<p><b>Legacy Combos</b></p>
	<p>Once you purchased 2 different Vanilla Legacies, you will be able to select their specific Legacy Combo upgrade.</p>
	<p>The current limit is one Legacy Combo - not including the additional one granted by the Research Revelation (F12000).</p>
	<p><b>Coin Cost</b>: 1 Tvg (1e72).</p>
	<p><b>Faction Coin Cost</b>: 1 Dc (1e33) of both Factions.</p>
