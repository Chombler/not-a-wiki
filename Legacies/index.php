	<h6><img src="/realm/Factions/picks/LegacyBanner.png"></h6>
	<p><b>Requirement</b>: Ascension 4 (R220+)</p>
	<p>This set of upgrade appears with no other unlock requirement.</p>
	<p>With each Legacy Container you can choose a Legacy (equal to the set of 3 faction upgrades of the same tier) that doesn't match your current faction.</p>
	<p>This unlocks those 3 faction upgrades for purchase for their normal coin cost (see faction upgrade costs at <a href="/realm/Ascension4" research="Ascension 4"><b>Ascension 4</b></a>).</p>
	<p>The menu below lists the exact three upgrades in every Legacy. Their effects are unchanged from the named upgrades on the corresponding <a href="/realm/Factions/"><b>Faction reference pages</b></a>.</p>
	<p>You can purchase more Legacies for a progressively increasing cost.</p>
	<p>The current limit is 4 paid Legacy Containers, plus the free special container granted by Relativity (F11750).</p>
	<p><b>Note</b>: Relativity&apos;s container does not increase the paid-container counter; the selected Legacy upgrades still retain their normal coin costs.</p>
	<p><b>Base Faction Legacy coin cost</b>: 1e39 * 1,000 ^ (0.5 * ((x + 3) ^ 2 - (x + 3))), where x is the paid container number.</p>
	<p><b>Base Faction Legacy Faction Coin cost</b>: 1e21 * 1e9 ^ (x - 1).</p>
	<p><b>Prestige Faction Legacy coin cost</b>: 1e118 * 1,000 ^ (0.5 * ((x + 3) ^ 2 - (x + 3))).</p>
	<p><b>Prestige Faction Legacy Faction Coin cost</b>: 1e45 * 1e9 ^ (x - 1).</p>
