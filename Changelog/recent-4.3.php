			<p onclick="shohid($(this));"><b> <a href="#" onclick="return false;">v4.3.0, Mar 26, 2025, Major Overhaul Update</a></b></p>
			<div class="autohide">
				<p><b>Official announcement</b>: <a href="https://www.divinegames.it/discuss/viewtopic.php?id=395&amp;p=8" target="_blank">Divine Games Developers' Diary</a></p>
				<p><b>NEW</b></p>
				<p>Added Lineage Perk 6s in Ascension 3.</p>
				<p>Building upgrade series are now removed starting from Ascension 3.</p>
				<p>Assistants upgrade series, alignment upgrade series, wall fragment series, gem potency series, and Sun Force are now removed starting from Ascension 4.</p>
				<p>Reintroduced Astral factions in Ascension 4.</p>
				<p>New Reincarnation Powers throughout all stages.</p>
				<p>New Secret Trophy.</p>
				<p>Arcane Brilliance now unlocks an upgrade that provides a bonus for each tier of the trophy unlocked.</p>
				<p>Added an upgrade for unlocking The Architect trophy.</p>
				<p><b>SYSTEM CHANGES</b></p>
				<p>Added Buy All Buildings button that attempts to buy all building tiers to the Buy Quantity setting.</p>
				<p>Added Autocast button modes to make the setup of autocasting spells easier and quicker.</p>
				<p>Clicking the lineage button once now buys them to the maximum level you can afford.</p>
				<p>Many wording changes, including renaming &quot;this game&quot; references to &quot;this Era&quot; and &quot;Elite/MAD factions&quot; to &quot;Astral factions&quot;.</p>
				<p>Mechanic consolidation and expansion: Triggered Tax Collections Power. In a similar way some Goblin upgrades already do, many other effects now make your spells cast free Tax Collections, additively or multiplicatively. Triggered Tax Collections aggregate into a single stat, in a similar way automatic clicks do.</p>
				<p>Clicks per second are also aggregated into a stat allowing for multiplicative increases.</p>
				<p>Reincarnation gems requirement and Coins required per Gem have been streamlined throughout all Ascensions except Ascension 0. As a result, you may find your next Abdication or Reincarnation requirements different from before.</p>
				<p>Royal Exchange container is now named Royal Market. Tooltip reworked for clarification. Royal Market bonus is now separated from the standard Ascension penalty system.</p>
				<p>The Buy Quantity button was reworked to a dropdown menu instead of cycling through buy modes.</p>
				<p>Added an option to disable toast messages.</p>
				<p><b>BALANCE CHANGES</b></p>
				<p>A lot of time-based requirements have been reduced throughout all game stages.</p>
				<p>All challenges, bloodlines, lineages and lineage perks, and artifact sets upgrades no longer suffer from Ascension penalties.</p>
				<p>Lineage perks are now unlocked asymmetrically: factions will distribute their perks across a large Reincarnation range and will unlock more through Ascensions. Lineages will have a hard cap of 25 levels per Ascension.</p>
				<p>Spells now suffer different Ascension Penalties based on their Tier, the higher the better. Spell tiers are now unlocked at a rate of one per Ascension, meaning that you can cast up to Tier 2 while in Ascension 1. Each spell also has additional effects per tier, and upgrades are challenge-locked. Previous tiers above maximum have been removed from existing saves, but you don&#039;t need to unlock them again if you already did. All spells, except extraordinary spells (Tax Collection with Round Table, Dragon&#039;s Breath, Catalyst, Twisting Nether, season spells), now follow this rule. Offline bonuses provided through tier upgrades have been assigned to their respective ascension. Mana cost multipliers increased for all spell tiers.</p>
				<p>As a special spell, Dragon&#039;s Breath now starts with 5 colors and unlock new ones across Ascensions. Its production effects will never suffer from Ascension penalties.</p>
				<p>Starting mana amount reduced to 500/1000 on starting a new Era.</p>
				<p>Ascension 3 Facility upgrades now provide Research Budget to their respective branch based on time spent in this Reincarnation with the time combinations of their faction representative.</p>
				<p>Ascension 3 Mercenaries now gain additional Research budget when they purchase spell contracts and union contracts; branches affected depend on factions selected.</p>
				<p>All Reincarnation powers unlocked after Ascension 0 now only start counting from the ascension they are unlocked in for their bases, with adjusted effect. For example, Reincarnation 50 power is based on (R-39), Reincarnation 120 power is based on (R-99).</p>
				<p>All Spell tier upgrades now also multiplicatively increase Faction Coins found while offline by 200% per tier (stacking additively with same sources).</p>
				<p>Angel, Demon and Faceless Bloodline now provide the ability to cast their alignment spell regardless of affiliation. If you already have that spell, its effect is increased.</p>
				<p>Base mana regen, and mana regen upgrade series have been increased.</p>
				<p>Excavation&#039;s faction coin generation base increased, scaling decreased. Excavations now always give Faction Coins.</p>
				<p>Excavation Resets now have a dynamic coin requirement of 3 orders of magnitude below the Reincarnation level, increasing by 1 each reset. You no longer lose anything by resetting excavations. You can no longer reset your excavations for free in Ascension 0, but you can still use Rubies.</p>
				<p>Many Faction upgrades, researches, lineages and challenge effects have been rebalanced and/or reworked.</p>
				<p>Removed usable restrictions from faction upgrades and researches that target or require specific game elements such as spells or Unique Buildings.</p>
				<p>Reverse Autocast is no longer a requirement for Tiered Autocast, they are now separate and independent upgrades.</p>
